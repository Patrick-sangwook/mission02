from quiz import Quiz
from quiz_game import QuizGame


# ============================================
# 기본 포켓몬 퀴즈 5개
# ============================================

default_quizzes = [

    Quiz(
        "피카츄의 타입은?",
        ["불", "전기", "물", "풀"],
        2
    ),

    Quiz(
        "이상해씨의 타입은?",
        ["불", "풀", "물", "전기"],
        2
    ),

    Quiz(
        "파이리의 타입은?",
        ["불", "물", "풀", "전기"],
        1
    ),

    Quiz(
        "꼬부기의 타입은?",
        ["불", "풀", "물", "전기"],
        3
    ),

    Quiz(
        "뮤는 환상의 포켓몬인가?",
        ["예", "아니오"],
        1
    )
]


# ============================================
# 게임 객체 생성
# ============================================

game = QuizGame(default_quizzes)


# ============================================
# 메인 메뉴
# ============================================

while True:

    print()
    print("==============================")
    print("🎯 포켓몬 퀴즈 게임 🎯")
    print("==============================")
    print("1. 퀴즈 풀기")
    print("2. 퀴즈 추가")
    print("3. 퀴즈 목록")
    print("4. 점수 확인")
    print("5. 종료")
    print("==============================")

    try:
        menu = int(
            input("번호를 선택하세요 : ")
        )

        # ------------------------------------
        # 1. 퀴즈 풀기
        # ------------------------------------

        if menu == 1:
            game.start_quiz()

        # ------------------------------------
        # 2. 퀴즈 추가
        # ------------------------------------

        elif menu == 2:

            print()
            print("==============================")
            print("➕ 새로운 퀴즈 추가")
            print("==============================")

            question = input(
                "문제를 입력하세요 : "
            )

            choices = []

            for i in range(4):
                choice = input(
                    f"선택지 {i + 1} : "
                )

                choices.append(choice)

            while True:

                try:
                    answer = int(
                        input(
                            "정답 번호를 입력하세요 (1~4) : "
                        )
                    )

                    if 1 <= answer <= 4:
                        break

                    print(
                        "⚠️ 1~4 사이의 번호를 입력하세요."
                    )

                except ValueError:
                    print(
                        "⚠️ 숫자만 입력하세요."
                    )

            new_quiz = Quiz(
                question,
                choices,
                answer
            )

            game.add_quiz(new_quiz)

            print()
            print("✅ 퀴즈가 추가되었습니다.")

        # ------------------------------------
        # 3. 퀴즈 목록
        # ------------------------------------

        elif menu == 3:
            game.show_quizzes()

        # ------------------------------------
        # 4. 점수 확인
        # ------------------------------------

        elif menu == 4:
            game.show_score()

        # ------------------------------------
        # 5. 종료
        # ------------------------------------

        elif menu == 5:

            print()
            print(
                "👋 포켓몬 퀴즈 게임을 종료합니다."
            )

            break

        else:
            print()
            print(
                "⚠️ 1~5 사이의 번호를 입력하세요."
            )

    except ValueError:

        print()
        print("⚠️ 숫자만 입력하세요.")